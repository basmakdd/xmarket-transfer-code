"""RQ2 rolling-origin check: local vs pool on the calendar split at three cutoff pairs (reviewer comment on temporal
evaluation). Origins: 60/70 and 70/80 (experiment group rq2roll, data variants cal6070 / cal7080) and the paper's 80/90
(group rq2). Inputs: paper/raw/rq2_<MODEL>_calendar<tag>.jsonl, tag in {_cal6070, _cal7080, ''}.

Per origin and model: contexts, median and mean pool - local NDCG@10, share of contexts with a positive difference,
Wilcoxon signed-rank p-value. Across origins (contexts present at all three): share whose sign is the same at every
origin. Outputs: paper/results/rq2_roll.csv, paper/results/rq2_roll_contexts.csv, paper/tables_rq2_roll.tex.
"""
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from common import REPO, PAPER_RAW

import os, json
import numpy as np, pandas as pd
from scipy.stats import wilcoxon

ORIGINS = [('_cal6070', '60/70'), ('_cal7080', '70/80'), ('', '80/90')]
MODELS = ['MostPop', 'ItemKNN', 'EASE']
rows = []
for tag, lab in ORIGINS:
    for m in MODELS:
        fn = f'{PAPER_RAW}/rq2_{m}_calendar{tag}.jsonl'
        if not os.path.exists(fn): continue
        for l in open(fn, encoding='utf-8'):
            r = json.loads(l)
            if 'pool' in r:
                rows.append({'origin': lab, 'model': m, 't': r['t'], 'local': r['local']['ndcg'], 'pool': r['pool']['ndcg']})
if not rows:
    raise SystemExit('rq2_roll_tables.py: no rolling-origin records yet (python run.py experiments --only rq2roll); skipped')
X = pd.DataFrame(rows).drop_duplicates(['origin', 'model', 't'], keep='last')
X['d'] = X.pool - X.local
S = []
for (o, m), g in X.groupby(['origin', 'model'], sort=False):
    nz = g.d[g.d != 0]
    S.append({'origin': o, 'model': m, 'contexts': len(g), 'median_d': g.d.median(), 'mean_d': g.d.mean(),
              'share_positive': (g.d > 0).mean(), 'wilcoxon_p': wilcoxon(nz).pvalue if len(nz) >= 5 else np.nan})
S = pd.DataFrame(S)
W = X.pivot_table(index=['model', 't'], columns='origin', values='d')
full = W.dropna()
agree = (np.sign(full).nunique(axis=1) == 1).groupby(level='model').mean() if len(full) else pd.Series(dtype=float)
S['sign_stable_share'] = S.model.map(agree)
S['contexts_all_origins'] = S.model.map(full.groupby(level='model').size() if len(full) else {})
os.makedirs(f'{REPO}/paper/results', exist_ok=True)
S.to_csv(f'{REPO}/paper/results/rq2_roll.csv', index=False, lineterminator='\n')
X.to_csv(f'{REPO}/paper/results/rq2_roll_contexts.csv', index=False, lineterminator='\n')
print(S.to_string(index=False))

L = ['% Auto-generated by paper/code/rq2_roll_tables.py. Requires booktabs.', '\\begin{table}[t]\\centering\\small',
     '\\caption{Rolling-origin check of RQ2 on the calendar split: pool $-$ local NDCG@10 at three cutoff pairs '
     '(percentiles of the category\'s dates). Sign stable: share of the contexts evaluated at all three origins whose '
     'difference has the same sign at every origin.}\\label{tab:rq2_roll}',
     '\\begin{tabular}{llrrrrrr}', '\\toprule',
     'Model & Origin & Contexts & Median & Mean & Share $>0$ & Wilcoxon $p$ & Sign stable \\\\', '\\midrule']
for m in MODELS:
    for _, r in S[S.model == m].iterrows():
        p = '--' if np.isnan(r.wilcoxon_p) else f'{r.wilcoxon_p:.3g}'
        ss = '--' if pd.isna(r.sign_stable_share) else f'{r.sign_stable_share:.2f}'
        L.append(f'{m} & {r.origin} & {r.contexts} & {r.median_d:+.4f} & {r.mean_d:+.4f} & {r.share_positive:.2f} & {p} & {ss} \\\\')
L += ['\\bottomrule', '\\end{tabular}', '\\end{table}']
open(f'{REPO}/paper/tables_rq2_roll.tex', 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')

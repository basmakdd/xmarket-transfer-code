"""Supplementary Tables S6 (per-context experiment accounting) and S7 (top-10 overlap by shared-catalog size,
distribution of the RQ1 local-agreement denominators, launch-set skips).

Added in round 3 so that a reader without repository access can check which context enters which experiment and why,
and the two RQ1 diagnostics the editor asked for. Reads only shipped machine-readable outputs:
  paper/raw/aud_accounting.csv         per experiment x context inclusion and exclusion reason (accounting.py)
  paper/raw/sc_UserKNN_random.jsonl    UserKNN scarcity coverage at f = 0.10 (the accounting row counts f = 0.05)
  paper/results/rq1_T3.csv             RQ1 top-10 overlap by shared-catalog bin (rq1_tables.py)
  paper/results/rq1_denominators.csv   distribution of local agreement L (rq1_tables.py)
  paper/results/l3_skips_summary.csv   launch skips (launch3_tables.py)
Writes paper/supp/S6.tex, paper/supp/S7.tex. Run after the other table scripts (run.py tables runs it after supp_tables.py).
"""
import os, sys, json
import numpy as np, pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from supp_tables import RAW, RES, OUT, write, ctx, MK, CAT  # shared helpers (supp_tables.py runs its tables only under __main__)

A = pd.read_csv(os.path.join(RAW, 'aud_accounting.csv'), encoding='utf-8')
CODE = {'nodonor': 'D', 'rq1rule': 'S', 'catalog': 'C', 'launch': 'U', 'launchp': 'P', 'costrule': 'R', 'cost': 'B',
        'incomplete': 'I', 'merge': 'M', 'subset': 'O', 'error': 'E'}
COLS = [('rq1_agree', 'RQ1', 'pairs'),
        ('rq2_MostPop_random', 'MP', 'reps'), ('rq2_ItemKNN_random', 'IK', 'reps'), ('rq2_EASE_random', 'EA', 'reps'), ('rq2_UserKNN_random', 'UK', 'reps'),
        ('rq2_ItemKNN_temporal', 'IK', 'reps'), ('rq2_ItemKNN_calendar', 'IK', 'reps'), ('rq2_EASE_calendar', 'EA', 'reps'),
        ('mkt_runs', 'GMF', 'reps'),
        ('sc_ItemKNN_random|arm=P', 'IK', 'sc'), ('sc_EASE_random|arm=P', 'EA', 'sc'), ('sc_UserKNN_random|arm=P', 'UK', 'sc'),
        ('sc_ItemKNN_temporal|arm=P', 'IK', 'sc'), ('sc_ItemKNN_calendar|arm=P', 'IK', 'sc'),
        ('l3_ItemKNN_random', 'IK', 'sc'), ('l3_ItemKNN_temporal', 'IK', 'sc'), ('l3_ItemKNN_calendar', 'IK', 'sc'),
        ('aud_single', 'IK', 'pairs')]
GROUPS = [('RQ1', 1), ('RQ2 random', 4), ('RQ2 Ch', 1), ('RQ2 Ca', 2), ('RQ2', 1), ('Scarcity R', 3), ('Sc. Ch', 1), ('Sc. Ca', 1),
          ('Launch R/Ch/Ca', 3), ('Single donor', 1)]

# UserKNN scarcity: coverage at f = 0.10 from the records (the accounting row is for f = 0.05, see supp_tables.s3)
uk = {}
p = os.path.join(RAW, 'sc_UserKNN_random.jsonl')
if os.path.exists(p):
    d = pd.DataFrame([json.loads(l) for l in open(p, encoding='utf-8')])
    d = d[(d.f == 0.1) & (d.arm == 'P') & (d.fb == 0) & d.err.isna() & d.ndcg.notna()]
    ok = d.groupby(['t', 'seed']).foreign.nunique()
    uk = ok[ok == 2].groupby('t').size().to_dict()

contexts = sorted(A.context.unique(), key=lambda t: (t.split(' ', 1)[1], t))
cells = {}
for exp, _, kind in COLS:
    x = A[A.experiment == exp].set_index('context')
    for t in contexts:
        if exp == 'sc_UserKNN_random|arm=P':
            if t in uk: v = str(uk[t])
            elif t in x.index and not x.loc[t, 'included'] and isinstance(x.loc[t, 'reason_code'], str): v = CODE.get(x.loc[t, 'reason_code'], '?')
            else: v = 'B'
        elif t not in x.index: v = '--'          # experiment universe excludes the context (calendar: 69 contexts)
        else:
            r = x.loc[t]
            if r.included:
                if kind == 'pairs': v = str(int(r.pairs_done))
                elif kind == 'sc': v = str(int(r.completed_reps)) if pd.notna(r.completed_reps) and r.completed_reps > 0 else '1'
                else: v = '\\checkmark'
            else: v = CODE.get(r.reason_code, '?')
        cells[(t, exp)] = v

L = ['% Auto-generated by paper/code/supp_extra.py from paper/raw/aud_accounting.csv. Requires longtable, booktabs, amssymb.',
     '{\\scriptsize\\setlength{\\tabcolsep}{2.2pt}',
     '\\begin{longtable}{l' + 'c' * len(COLS) + '}',
     '\\caption{Table S6. Per-context experiment accounting.}\\label{tab:S6}\\\\', '\\toprule',
     ' & ' + ' & '.join(f'\\multicolumn{{{n}}}{{c}}{{{g}}}' for g, n in GROUPS) + ' \\\\',
     'Context & ' + ' & '.join(lab for _, lab, _ in COLS) + ' \\\\', '\\midrule', '\\endfirsthead',
     '\\caption[]{Table S6 (continued).}\\\\', '\\toprule',
     ' & ' + ' & '.join(f'\\multicolumn{{{n}}}{{c}}{{{g}}}' for g, n in GROUPS) + ' \\\\',
     'Context & ' + ' & '.join(lab for _, lab, _ in COLS) + ' \\\\', '\\midrule', '\\endhead',
     '\\bottomrule', '\\multicolumn{%d}{p{0.95\\linewidth}}{\\scriptsize Number: completed target--donor pairs (RQ1; single-donor runs, all same-category donors, of which the RQ4 tests use the RQ1 pairs without IN Arts \\& Crafts) or repetitions (scarcity subsamples at $f=0.10$, launch sets); '
     '\\checkmark: included (one run). Letters: excluded, codes as in Table S3 (D no same-category donor; S no donor shares $\\geq$10 products; C catalog over 4,000 products (EASE); '
     'U fewer than 10 launched-item test users; P too few launched or eligible products; R compute rule fixed before the run; B not run within the compute budget; '
     'I incomplete; O outside the analysed subset). --: not in the experiment universe (calendar split: 69 contexts). '
     'MP MostPop, IK ItemKNN, EA EASE, UK UserKNN, GMF MA-GMF and GMF controls; R random, Ch chronological, Ca calendar split.} \\\\' % (len(COLS) + 1),
     '\\endfoot']
for t in contexts:
    L.append(ctx(t) + ' & ' + ' & '.join(cells[(t, e)] for e, _, _ in COLS) + ' \\\\')
L += ['\\end{longtable}}']
write('S6.tex', L)

# ---------------------------------------------------------------------------------------------- S7
T3 = pd.read_csv(os.path.join(RES, 'rq1_T3.csv'), encoding='utf-8')
T3 = T3[(T3.variant.isin(['main', ''])) | T3.variant.isna()] if 'variant' in T3 else T3
DN = pd.read_csv(os.path.join(RES, 'rq1_denominators.csv'), encoding='utf-8')
SK = pd.read_csv(os.path.join(RES, 'l3_skips_summary.csv'), encoding='utf-8')
def f3(v): return '--' if pd.isna(v) else f'{v:.2f}'
def s3(v): return '--' if pd.isna(v) else (f'{v:+.2f}').replace('-', '$-$')
L = ['% Auto-generated by paper/code/supp_extra.py. Requires booktabs, adjustbox.', '\\begin{table}[H]',
     '\\caption{Table S7. RQ1 diagnostics and launch skips.}', '\\label{tab:S7}', '\\centering', '\\small',
     '\\begin{adjustbox}{max width=\\linewidth}', '\\begin{tabular}{lrrrrrrr}', '\\toprule',
     '\\multicolumn{8}{l}{\\textit{(a) Top-10 overlap by number of shared products (all foreign data; median over pairs, 95\\% CI)}} \\\\',
     'Shared products & Pairs & Median shared & Chance $10/n$ & Local $L$ & Foreign $F$ & $F-c$ (95\\% CI) & $D=F-L$ (95\\% CI) \\\\', '\\midrule']
for r in T3[T3.arm == 'all'].itertuples():
    L.append(f'{r.bin} & {r.pairs} & {r.median_shared:.0f} & {f3(r.chance)} & {f3(r.local)} & {f3(r.foreign)} & {s3(r.foreign_excess)} [{s3(r.foreign_excess_lo)}, {s3(r.foreign_excess_hi)}] & {s3(r.D)} [{s3(r.D_lo)}, {s3(r.D_hi)}] \\\\')
L += ['\\midrule', '\\multicolumn{8}{l}{\\textit{(b) Local agreement $L$ (denominator of the ratio sensitivity check), pairs with defined $L$ (Table 1 also needs a defined $F$)}} \\\\',
      'Measure & Pairs & Min & P5 / P25 & Median & P75 / Max & $L<0.05$ / $<0.10$ / $<0.20$ & $L\\leq 0$ \\\\', '\\midrule']
MN = {'sp': 'Rank correlation', 'top10': 'Top-10 overlap', 'cos': 'Co-interaction cosine', 'nbr5': '5-NN overlap', 'ppmi': 'PPMI cosine', 'resid': 'Residual cosine'}
for _, r in DN[DN.arm == 'all'].iterrows():
    L.append(f"{MN.get(r['measure'], r['measure'])} & {r['n']} & {f3(r['min']).replace('-', '$-$')} & {f3(r['p05'])} / {f3(r['p25'])} & {f3(r['median'])} & {f3(r['p75'])} / {f3(r['max'])} & "
             f"{r['n_below_0.05']} / {r['n_below_0.10']} / {r['n_below_0.20']} & {r['n_nonpositive']} \\\\")
L += ['\\midrule', '\\multicolumn{8}{l}{\\textit{(c) Launch sets or contexts skipped (ItemKNN; the other models are skipped identically, EASE also above 4,000 products)}} \\\\',
      'Split & \\multicolumn{3}{l}{Reason} & Level & Records & Contexts & \\\\', '\\midrule']
SPLN = {'random': 'random', 'temporal': 'chronological', 'calendar': 'calendar'}
for r in SK[SK.model == 'ItemKNN'].itertuples():
    L.append(f'{SPLN.get(r.split, r.split)} & \\multicolumn{{3}}{{l}}{{{r.reason}}} & {r.level} & {r.n_records} & {r.n_contexts} & \\\\')
L += ['\\bottomrule', '\\end{tabular}', '\\end{adjustbox}', '\\par\\vspace{2pt}{\\footnotesize Panel (a): chance $c=10/n$ for $n$ shared products; with 10--19 shared products the top-10 lists cover most of the shared catalog, so overlap is close to chance and rank correlation carries more weight. '
      'Panel (c): launched products are chosen without consulting the test set; a launch set is evaluated only if at least 10 test users have a launched-product test interaction, because launched-item NDCG@10 is undefined without them.\\par}',
      '\\end{table}']
write('S7.tex', L)

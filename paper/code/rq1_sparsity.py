"""RQ1 paired comparison by sparsity (Supplementary Table S8).

Editor (round 2): the agreement measures differ in chance level, scale and sensitivity to sparsity. This script shows
whether the main RQ1 comparison -- patterns lose less cross-country agreement than popularity, D_pat - D_pop > 0 within
each target-donor pair -- depends on how sparse the pair's data are. Two sparsity measures, binned with cut points fixed
here before looking at results:
  * shared products n_shared: 10-19, 20-49, 50-199, >=200 (as in rq1_tables.py)
  * local density on the shared products: local interactions on shared products per shared product (nT_shared / n_shared),
    in quartiles over the 324 pairs.
Per bin: pairs, share of pairs with D_pat - D_pop > 0, and the median with a two-way cluster-bootstrap 95% CI (boot.py),
for cosine vs rank correlation and for 5-NN overlap vs top-10 overlap. Inputs: paper/raw/rq1_agree.jsonl (original data).
Self-check: the 'all pairs' rows reproduce Table 1 (paper/results/rq1_T2.csv).
Outputs: paper/results/rq1_sparsity.csv, paper/supp/S8.tex
"""
import os as _os, sys as _sys
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from common import REPO, PAPER_RAW

import numpy as np, pandas as pd
import boot

X = pd.read_json(f'{PAPER_RAW}/rq1_agree.jsonl', lines=True).drop_duplicates(['t', 'donor_market'])
X = X[X.n_shared >= 10].copy()
X['dens'] = X.nT_shared / X.n_shared
X['pc'] = (X.for_cos - X.loc_cos) - (X.for_sp - X.loc_sp)          # D_cos - D_rank
X['pn'] = (X.for_nbr5 - X.loc_nbr5) - (X.for_top10 - X.loc_top10)  # D_5NN - D_top10
q = X.dens.quantile([0.25, 0.5, 0.75]).values
groups = [('all pairs', 'All pairs', X.n_shared >= 10)]
for a, b in [(10, 19), (20, 49), (50, 199), (200, 10 ** 9)]:
    groups.append(('shared', f'{a}--{b}' if b < 10 ** 8 else f'$\\geq${a}', (X.n_shared >= a) & (X.n_shared <= b)))
edges = [-np.inf, *q, np.inf]
for k in range(4):
    lo, hi = edges[k], edges[k + 1]
    lab = (f'Q{k + 1}: $\\leq${hi:.1f}' if k == 0 else f'Q{k + 1}: $>${lo:.1f}' if k == 3 else f'Q{k + 1}: {lo:.1f}--{hi:.1f}')
    groups.append(('density', lab, (X.dens > lo) & (X.dens <= hi)))
rows = []
for kind, lab, m in groups:
    r = dict(kind=kind, bin=lab)
    for col, nm in [('pc', 'cos_vs_rank'), ('pn', 'nn_vs_top10')]:
        z = X[m & X[col].notna()]
        v, l, h = boot.summarize(z[col].values, z.target_market.values, z.category.values, donors=z.donor_market.values,
                                 stat='median', label=f'rq1_sparsity|{nm}|{kind}|{lab}')
        r.update({f'{nm}_pairs': len(z), f'{nm}_share': float((z[col] > 0).mean()) if len(z) else np.nan,
                  f'{nm}_median': v, f'{nm}_lo': l, f'{nm}_hi': h})
    rows.append(r)
R = pd.DataFrame(rows)
R.to_csv(f'{REPO}/paper/results/rq1_sparsity.csv', index=False, lineterminator='\n')
print(R.round(3).to_string(index=False))

# self-check against Table 1 (paired rows, all foreign data)
T2 = pd.read_csv(f'{REPO}/paper/results/rq1_T2.csv')
T2 = T2[(T2.variant == 'main') & (T2.arm == 'all') & (T2.threshold.isna() if 'threshold' in T2 else True)]
a = R.iloc[0]
print('CHECK all pairs: cos-vs-rank share', round(a.cos_vs_rank_share, 4), 'median', round(a.cos_vs_rank_median, 4),
      '| nn-vs-top10 share', round(a.nn_vs_top10_share, 4), 'median', round(a.nn_vs_top10_median, 4))
ref = T2[T2.scale.astype(str).str.startswith('D')].set_index(['pattern', 'popularity'])
for (pat, pop), nm in [(('cos', 'sp'), 'cos_vs_rank'), (('nbr5', 'top10'), 'nn_vs_top10')]:
    rr = ref.loc[(pat, pop)]
    rr = rr.iloc[0] if isinstance(rr, pd.DataFrame) else rr
    assert int(rr.pairs) == int(a[nm + '_pairs']) and abs(rr.share_pattern_higher - a[nm + '_share']) < 1e-12 and abs(rr['median'] - a[nm + '_median']) < 1e-12, nm
print('CHECK passed: all-pairs rows equal Table 1 (pairs, share, median)')
# the all-pairs interval is Table 1's own (rq1_tables.py), so the two tables show the same row
for (pat, pop), nm in [(('cos', 'sp'), 'cos_vs_rank'), (('nbr5', 'top10'), 'nn_vs_top10')]:
    rr = ref.loc[(pat, pop)]; rr = rr.iloc[0] if isinstance(rr, pd.DataFrame) else rr
    R.loc[0, nm + '_lo'], R.loc[0, nm + '_hi'] = rr.lo, rr.hi
R.to_csv(f'{REPO}/paper/results/rq1_sparsity.csv', index=False, lineterminator='\n')

def s(v): return '--' if pd.isna(v) else f'{v:+.2f}'.replace('-', '$-$')
def cell(r, nm):
    return (f"{int(r[nm + '_pairs'])} & {100 * r[nm + '_share']:.0f}\\% & {s(r[nm + '_median'])} [{s(r[nm + '_lo'])}, {s(r[nm + '_hi'])}]"
            if r[nm + '_pairs'] else '0 & -- & --')
L = ['% Auto-generated by paper/code/rq1_sparsity.py from paper/raw/rq1_agree.jsonl. Requires booktabs, adjustbox.',
     '\\begin{table}[H]', '\\caption{Table S8. RQ1 paired comparison by sparsity.}', '\\label{tab:S8}', '\\centering', '\\small',
     '\\begin{adjustbox}{max width=\\linewidth}', '\\begin{tabular}{lrrlrrl}', '\\toprule',
     ' & \\multicolumn{3}{c}{Cosine vs rank correlation} & \\multicolumn{3}{c}{5-NN overlap vs top-10 overlap} \\\\',
     'Pairs grouped by & Pairs & $D_{\\mathrm{pat}}>D_{\\mathrm{pop}}$ & Median $D_{\\mathrm{pat}}-D_{\\mathrm{pop}}$ (95\\% CI) & Pairs & $D_{\\mathrm{pat}}>D_{\\mathrm{pop}}$ & Median (95\\% CI) \\\\', '\\midrule']
cur = None
for _, r in R.iterrows():
    if r.kind != cur:
        if r.kind == 'shared': L += ['\\midrule', '\\multicolumn{7}{l}{\\textit{Number of shared products}} \\\\']
        if r.kind == 'density': L += ['\\midrule', '\\multicolumn{7}{l}{\\textit{Local interactions per shared product (quartiles)}} \\\\']
        cur = r.kind
    L.append(f"{r.bin} & {cell(r, 'cos_vs_rank')} & {cell(r, 'nn_vs_top10')} \\\\")
L += ['\\bottomrule', '\\end{tabular}', '\\end{adjustbox}',
      '\\par\\vspace{2pt}{\\footnotesize\\noindent $D=F-L$ per measure as in Table 1 of the main text (all foreign data); $D_{\\mathrm{pat}}-D_{\\mathrm{pop}}>0$: patterns lose less agreement than popularity. '
      'Medians over target--donor pairs with two-way cluster-bootstrap 95\\% intervals. 5-NN overlap needs at least five products with five neighbours in both samples, so sparse pairs drop out of the right-hand columns. '
      'Bins were fixed before the results were seen.\\par}', '\\end{table}']
open(f'{REPO}/paper/supp/S8.tex', 'w', encoding='utf-8', newline='\n').write('\n'.join(L) + '\n')
print('wrote paper/results/rq1_sparsity.csv, paper/supp/S8.tex')
